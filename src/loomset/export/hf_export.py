from __future__ import annotations

import csv as _csv
import re
from pathlib import Path
from urllib.parse import urlparse, urlunparse

from datasets import Dataset


def _flat(text: str | None) -> str:
    """Collapse newlines/tabs to a single space — makes CSV spreadsheet-safe."""
    if not text:
        return ""
    return re.sub(r"\s+", " ", text).strip()


def _canonical_url(url: str) -> str:
    parsed = urlparse((url or "").strip())
    scheme = parsed.scheme.lower()
    hostname = (parsed.hostname or "").lower()
    port = parsed.port
    netloc = hostname
    if port and not ((scheme == "http" and port == 80) or (scheme == "https" and port == 443)):
        netloc = f"{hostname}:{port}"
    path = parsed.path.rstrip("/") or "/"
    return urlunparse((scheme, netloc, path, "", parsed.query, ""))


def _unique_records(records: list[dict]) -> list[dict]:
    unique: list[dict] = []
    seen_urls: set[str] = set()
    for record in records:
        url = _canonical_url(record.get("url", ""))
        if not url or url in seen_urls:
            continue
        seen_urls.add(url)
        unique.append({**record, "url": url})
    return unique


def export_dataset(records: list[dict], export_dir: str | Path) -> tuple[Path, Path, Path, Path]:
    export_path = Path(export_dir)
    export_path.mkdir(parents=True, exist_ok=True)
    records = _unique_records(records)

    # Full-fidelity records for JSON / Parquet (keep multi-line text)
    rich_records = [
        {
            "text": record.get("text") or "",
            "label": record.get("label") or "",
            "url": record.get("url") or "",
            "domain": record.get("domain") or "",
            "label_source": record.get("label_source") or "auto",
            "query": record.get("query") or "",
        }
        for record in records
    ]

    if rich_records:
        dataset = Dataset.from_list(rich_records)
    else:
        dataset = Dataset.from_dict({field: [] for field in ["text", "label", "url", "domain", "label_source", "query"]})

    dataset_path = export_path / "dataset.json"
    dataset.to_json(str(dataset_path))

    parquet_path = export_path / "dataset.parquet"
    dataset.to_parquet(str(parquet_path))

    # CSV — one record per row, text collapsed to a single line so url/domain
    # cells are never pushed into the wrong column by spreadsheet tools.
    csv_path = export_path / "dataset.csv"
    fieldnames = ["text", "label", "url", "domain", "label_source", "query"]
    with csv_path.open("w", newline="", encoding="utf-8") as fh:
        writer = _csv.DictWriter(fh, fieldnames=fieldnames, quoting=_csv.QUOTE_ALL)
        writer.writeheader()
        for record in records:
            writer.writerow({
                "text": _flat(record.get("text")),
                "label": record.get("label") or "",
                "url": record.get("url") or "",
                "domain": record.get("domain") or "",
                "label_source": record.get("label_source") or "auto",
                "query": record.get("query") or "",
            })

    # Dataset card
    label_dist: dict[str, int] = {}
    domains: set[str] = set()
    for r in records:
        lbl = r.get("label", "unknown")
        label_dist[lbl] = label_dist.get(lbl, 0) + 1
        dom = r.get("domain", "")
        if dom:
            domains.add(dom)

    label_lines = "\n".join(f"  - `{lbl}`: {cnt} records" for lbl, cnt in sorted(label_dist.items()))
    domain_lines = "\n".join(f"  - {d}" for d in sorted(domains)[:20]) if domains else "  - N/A"

    card_path = export_path / "README.md"
    card_path.write_text(
        "# LoomSet Dataset\n\n"
        "This dataset was generated by the LoomSet MVP pipeline.\n\n"
        "## Overview\n\n"
        f"- **Total records**: {len(records)}\n"
        f"- **Labels used**: {len(label_dist)}\n"
        "- **License**: CC-BY (user confirmation recommended)\n"
        "- **Source**: URLs discovered and processed locally with the LoomSet pipeline\n\n"
        "## Label Distribution\n\n"
        f"{label_lines}\n\n"
        "## Source Domains\n\n"
        f"{domain_lines}\n\n"
        "## Format\n\n"
        "Available in JSON, CSV, and Parquet formats.\n"
        "Each record contains: `text`, `label`, `url`, `domain`, `label_source`, `query`.\n\n"
        "> **CSV note**: the `text` column has newlines collapsed to spaces for spreadsheet\n"
        "> compatibility. Open `dataset.json` or `dataset.parquet` for full multi-line text.\n",
        encoding="utf-8",
    )
    return dataset_path, csv_path, parquet_path, card_path
